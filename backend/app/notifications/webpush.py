"""Web Push without third-party services: RFC 8291 payload encryption + RFC 8292 VAPID.

Uses only ``cryptography`` and ``PyJWT``, already pinned for the Microsoft login.
The keys belong to the institution and are generated by ``python -m app.cli
vapid-keys``; no account at Google, Apple or Mozilla is required.
"""

import base64
import os
import time
from urllib.parse import urlsplit

import jwt
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

RECORD_SIZE = 4096
# Browser push services only; the server never posts to arbitrary URLs (SSRF).
PUSH_HOST_SUFFIXES = (
    "fcm.googleapis.com",
    "push.services.mozilla.com",
    "push.apple.com",
    "notify.windows.com",
)


def b64decode(value):
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def b64encode(value):
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode("ascii")


def public_bytes(key):
    return key.public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )


def generate_vapid_keys():
    key = ec.generate_private_key(ec.SECP256R1())
    private = key.private_numbers().private_value.to_bytes(32, "big")
    return b64encode(private), b64encode(public_bytes(key.public_key()))


def load_private_key(value):
    raw = b64decode(value)
    if len(raw) != 32:
        raise ValueError("VAPID_PRIVATE_KEY deve ter 32 bytes em base64url")
    return ec.derive_private_key(int.from_bytes(raw, "big"), ec.SECP256R1())


def endpoint_allowed(endpoint):
    parts = urlsplit(endpoint)
    host = (parts.hostname or "").lower()
    return (
        parts.scheme == "https"
        and not parts.username
        and not parts.password
        and parts.port in (None, 443)
        and any(host == suffix or host.endswith("." + suffix) for suffix in PUSH_HOST_SUFFIXES)
    )


def encrypt(payload, p256dh, auth, sender_key=None, salt=None):
    """Encrypt ``payload`` for one subscription using the aes128gcm content coding."""
    receiver_raw = b64decode(p256dh)
    auth_secret = b64decode(auth)
    if len(receiver_raw) != 65 or len(auth_secret) != 16:
        raise ValueError("Chaves da inscrição inválidas")
    receiver = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), receiver_raw)
    sender_key = sender_key or ec.generate_private_key(ec.SECP256R1())
    sender_raw = public_bytes(sender_key.public_key())
    shared = sender_key.exchange(ec.ECDH(), receiver)
    ikm = HKDF(
        hashes.SHA256(),
        32,
        salt=auth_secret,
        info=b"WebPush: info\x00" + receiver_raw + sender_raw,
    ).derive(shared)
    salt = salt or os.urandom(16)
    cek = HKDF(hashes.SHA256(), 16, salt=salt, info=b"Content-Encoding: aes128gcm\x00").derive(ikm)
    nonce = HKDF(hashes.SHA256(), 12, salt=salt, info=b"Content-Encoding: nonce\x00").derive(ikm)
    if len(payload) > RECORD_SIZE - 17 - 86:
        raise ValueError("Conteúdo da notificação muito grande")
    ciphertext = AESGCM(cek).encrypt(nonce, payload + b"\x02", None)
    header = salt + RECORD_SIZE.to_bytes(4, "big") + bytes([len(sender_raw)]) + sender_raw
    return header + ciphertext


def vapid_headers(endpoint, private_key, public_key, subject, ttl_hours=12):
    parts = urlsplit(endpoint)
    claims = {
        "aud": f"{parts.scheme}://{parts.netloc}",
        "exp": int(time.time()) + ttl_hours * 3600,
        "sub": subject,
    }
    token = jwt.encode(claims, load_private_key(private_key), algorithm="ES256")
    return {"Authorization": f"vapid t={token}, k={public_key}"}
